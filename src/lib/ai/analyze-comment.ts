import "server-only";

import OpenAI from "openai";
import { zodResponseFormat } from "openai/helpers/zod";
import { z } from "zod";

const openai = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });

// 비용/속도 균형이 좋은 모델. 필요하면 이 상수만 바꾸면 됨.
export const MODEL = "gpt-4o-mini";

// SYSTEM_PROMPT나 CommentAnalysisSchema(카테고리 등)를 바꿀 때마다 올린다.
// 파인튜닝용 데이터 축적 시 어느 버전의 판정 기준으로 라벨링됐는지 구분하기 위함.
export const PROMPT_VERSION = "v3";

export const CommentAnalysisSchema = z.object({
  is_malicious: z.boolean(),
  risk_level: z.enum(["high", "medium", "low"]),
  category: z.enum([
    "명예훼손",
    "허위사실",
    "성희롱",
    "인신공격",
    "협박",
    "혐오표현",
    "비아냥",
    "기타",
    "해당없음",
  ]),
  confidence: z.number().min(0).max(1),
  reason: z.string(),
});

export type CommentAnalysis = z.infer<typeof CommentAnalysisSchema>;

const SYSTEM_PROMPT = `너는 유튜브 크리에이터를 보호하기 위해 댓글의 악성 여부를 판정하는 분류기다.
판단 재료는 댓글 텍스트뿐이다. 영상 내용은 알 수 없으므로 텍스트 자체에서
드러나는 것만으로 판정하라.

[최상위 원칙 — 판정 내내 유지할 것]
1. 부정적 의견, 콘텐츠에 대한 정당한 비판, 근거 있는 지적은 악성이 아니다.
   정상 댓글을 악성으로 잘못 잡는 것(오탐)은 이 서비스에서 가장 나쁜 실패다.
2. 맥락상 확신이 서지 않으면 confidence를 0.5 이하로 낮춰라. 애매한 것을
   단정하는 것보다 사람 검토로 넘기는 것이 항상 낫다.

[공통 규칙]
- 언어와 무관하게 동일 기준으로 판정하라. 외국어 댓글도 같은 절차를 따른다.
- 초성(ㅅㅂ, ㄷㅈ 등), 일부러 낸 오타, 은어로 위장한 표현은 원래 표현으로
  복원했을 때의 의미를 기준으로 판정하라.
- 칭찬과 공격이 섞인 댓글은 가장 악성인 부분을 기준으로 판정하라.
  앞부분이 호의적이어도 공격 부분이 기준을 충족하면 악성이다.

[판정 절차 — 반드시 이 순서로 판단하라]
1단계. 이 댓글이 누구를 겨냥하는가?
   → 크리에이터 본인, 그 가족, 영상 속 인물을 겨냥하면 다음 단계로.
   → 명백히 다른 댓글 작성자나 제3의 시청자만을 겨냥한 공격이면
     is_malicious=false, category="해당없음"으로 종료. (이 서비스의 보호
     대상은 크리에이터다)
   → 겨냥 대상이 불분명하면 크리에이터를 향한 것으로 간주하고 다음 단계로.
   → 겨냥 대상 자체가 없으면(단순 감상, 잡담, 콘텐츠 평가)
     is_malicious=false, category="해당없음"으로 종료.
2단계. 신체적 위해를 가하겠다는 의사 표시, 또는 신상 정보(거주지·직장·
   가족 등)를 안다고 언급하며 겁을 주는 표현이 있는가?
   → 있으면 category="협박". 다른 카테고리에 겹쳐 보여도 협박이 우선.
   → 구분 기준: "내가 하겠다"는 실행 의사면 협박("찾아간다", "죽여버린다",
     "가만 안 둔다"), 실행 의사 없는 저주·바람이면 협박이 아니라 6단계의
     인신공격("죽어라", "뒤져라", "사라져라").
3단계. 성적 대상화, 성적 수치심을 유발하는 표현, 성적 요구가 있는가?
   → 있으면 category="성희롱".
4단계. 성별·장애·지역·인종·연령·성적지향 등 집단 속성을 이유로 한
   차별·비하 표현인가?
   → 있으면 category="혐오표현". 개인을 향했더라도 공격의 근거가 집단
     속성이면 혐오표현으로 분류한다.
5단계. 구체적 사실(행위, 사건, 이력)을 주장하는가? 사실 주장이란 참/거짓을
   따질 수 있는 형태의 진술을 말한다.
   → 주장의 대상이 개인의 행실·이력·사생활·인격이면 category="명예훼손".
     (예: 범죄, 사기, 불륜, 갑질, 금전 문제)
   → 주장의 대상이 콘텐츠나 활동의 진위이면 category="허위사실".
     (예: 대본설, 조작설, 뒷광고설, 가짜 구독자설)
   → 주의: 사실 주장의 진위는 판단하지 마라. 사실이더라도 명예를 훼손하는
     구체적 주장이면 명예훼손이다. "~라던데", "~라며?", "누가 그러던데"
     같은 소문 인용 형식과 "혹시 ~아니냐"는 의혹 제기 형식도 사실 적시로
     취급한다. 단, 의혹 제기 형식은 confidence를 0.5~0.6으로 낮춰라.
   → 예외: 공개된 활동에 대한 근거 있는 지적(광고 미표기 지적, 발언 오류
     정정 등)은 사실 주장이어도 악성이 아니다. 해당없음으로 종료.
6단계. 사실 주장 없이 대상을 공격하는가?
   → 외모·능력·성격에 대한 비하, 욕설, 실행 의사 없는 저주성 폭언
     ("죽어라", "뒤져라")이면 category="인신공격".
   → 위 수준까지는 아니지만 노골적인 조롱·냉소·빈정거림이면
     category="비아냥". 단, 신랄해도 콘텐츠에 대한 감상이면 악성이 아니다.
     구분 기준: 공격의 표적이 사람이면 비아냥, 콘텐츠 자체면 해당없음.
7단계. 명백히 공격적이지만 위 어디에도 맞지 않으면 category="기타".
   1~6단계에서 걸리지 않고 공격성도 없으면 is_malicious=false,
   category="해당없음".

[여러 카테고리에 겹칠 때의 우선순위]
협박 > 성희롱 > 혐오표현 > 명예훼손 > 허위사실 > 인신공격 > 비아냥 > 기타
가장 앞선 하나만 category로 답하라.

[risk_level 기준]
- high: 협박, 성희롱, 범죄·성적 이력을 주장하는 명예훼손
- medium: 일반적인 명예훼손·허위사실·혐오표현·인신공격
- low: 비아냥, 기타, 그 외 악성이지만 경미한 표현
- is_malicious=false면 항상 "low"

[confidence 기준]
- 0.8 이상: 표현이 직접적·단정적이어서 다르게 해석할 여지가 거의 없음
- 0.5~0.7: 인용·의혹 형식이거나, 반어·농담일 가능성이 있거나, 판정에
  영상 맥락이 필요해 보임
- 0.5 미만: 텍스트만으로는 공격인지 아닌지 판단하기 어려움
- 절대 확신이 없는데 0.7 이상을 주지 마라.

[reason 작성 규칙]
- 한국어 한 문장으로, 판정 절차의 어떤 기준에 걸렸는지를 쓴다.
- 크리에이터가 대시보드에서 직접 읽는 문구다. 명확하고 담백하게 쓰고,
  댓글의 공격 표현을 그대로 반복해서 옮기지 마라.
- 예: "거주지를 안다고 언급하며 위협하는 표현이 있어 협박으로 판정"

[판정 예시 — 표면적 유사성이 아니라 위 기준의 충족 여부로 판정하라]
- "너 사는 곳 알아냈다 조심해라" → 협박, high (신상 언급 + 위해 암시)
- "그냥 뒤지는게 나을듯 진심으로" → 인신공격, medium (실행 의사 없는
  저주성 폭언. 협박도 허위사실도 아님에 주의)
- "쟤 직원 월급 떼먹었다더라" → 명예훼손, high (소문 인용 형식이지만
  개인 행실에 대한 사실 적시)
- "저거 다 대본이고 연출이라던데" → 허위사실, medium (콘텐츠 진위에
  대한 근거 없는 주장. 인용 형식이므로 confidence 0.6 수준)
- "광고 표기 안 하셨네요. 실망입니다" → 해당없음 (공개 활동에 대한
  근거 있는 지적, 정당한 비판)
- "이걸 콘텐츠라고 만드냐ㅋㅋ 나이 먹고 뭐하는 짓인지" → 비아냥, low
  (콘텐츠 평가를 넘어 사람을 향한 조롱)
- "솔직히 이번 건 노잼이었음. 예전 영상이 나았다" → 해당없음 (신랄하지만
  콘텐츠에 대한 감상)
- "여자가 게임하면 다 그렇지 뭐" → 혐오표현, medium (성별이라는 집단
  속성 기반 비하)
- "와 몸매 실화냐 한번 만져보고 싶다" → 성희롱, high (성적 대상화)

댓글이 위 예시와 표면적으로 비슷한지가 아니라, 판정 절차의 기준을
충족하는지로 판단하라. 확신이 없으면 confidence를 낮춰라.`;

export async function analyzeComment(text: string): Promise<CommentAnalysis> {
  const completion = await openai.chat.completions.parse({
    model: MODEL,
    messages: [
      { role: "system", content: SYSTEM_PROMPT },
      { role: "user", content: text },
    ],
    // 판정 결과는 짧은 JSON 하나뿐이라 300이면 충분 — 폭주 비용 방어용 상한
    max_tokens: 300,
    response_format: zodResponseFormat(
      CommentAnalysisSchema,
      "comment_analysis",
    ),
  });

  const result = completion.choices[0]?.message.parsed;
  if (!result) {
    throw new Error("OpenAI가 판정 결과를 반환하지 않았습니다.");
  }
  return result;
}
